/**
 * Record the SHA-256 of each OCR language pack.
 *
 * The catalogue refuses to install a pack it has no verified digest for, so
 * this table is what makes the download feature work at all. It is generated
 * rather than hand-written, and generated from the SAME pinned tag the app
 * downloads from - a digest recorded against a different tag would reject
 * every honest download.
 *
 *   node scripts/ocr-checksums.mjs            # every language, both sets
 *   node scripts/ocr-checksums.mjs deu fra    # just these
 *
 * Writes src/ocr/checksums.generated.ts. Re-run it when TESSDATA_TAG changes;
 * the digests are tag-specific and stale ones fail closed, not open.
 */
import { createHash } from 'node:crypto'
import { writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const src = await import(`file://${join(here, '../src/ocr/languages.ts')}`).catch(() => null)

// The catalogue is TypeScript, so read the values out of the source rather than
// importing it - this script runs under plain node, with no transpiler.
const text = await (await import('node:fs/promises')).readFile(join(here, '../src/ocr/languages.ts'), 'utf8')
const TAG = /TESSDATA_TAG = '([^']+)'/.exec(text)?.[1]
const codes = [...text.matchAll(/code: '([a-z_]+)'/g)].map((m) => m[1])
if (!TAG || codes.length === 0) throw new Error('could not read the catalogue')

const wanted = process.argv.slice(2)
const targets = wanted.length > 0 ? codes.filter((c) => wanted.includes(c)) : codes
const url = (code, set) =>
  `https://raw.githubusercontent.com/tesseract-ocr/${set === 'best' ? 'tessdata_best' : 'tessdata_fast'}/${TAG}/${code}.traineddata`

const rows = []
for (const code of targets) {
  for (const set of ['fast', 'best']) {
    process.stdout.write(`  ${code}/${set} ... `)
    try {
      const res = await fetch(url(code, set))
      if (!res.ok) {
        console.log(`HTTP ${res.status} - skipped`)
        continue
      }
      const bytes = Buffer.from(await res.arrayBuffer())
      const digest = createHash('sha256').update(bytes).digest('hex')
      rows.push({ code, set, digest, size: bytes.length })
      console.log(`${digest.slice(0, 16)}… (${Math.round(bytes.length / 1024)} KB)`)
    } catch (err) {
      console.log(`failed: ${err.message}`)
    }
  }
}

const body = rows.map((r) => `  '${r.code}:${r.set}': { sha256: '${r.digest}', size: ${r.size} },`).join('\n')
await writeFile(
  join(here, '../src/ocr/checksums.generated.ts'),
  `/* eslint-disable */
// GENERATED by scripts/ocr-checksums.mjs — do not edit.
// Digests are specific to tessdata tag ${TAG}. Re-run after changing it.

export interface PackDigest {
  sha256: string
  size: number
}

/** Keyed \`\${code}:\${set}\`. A missing entry means the pack cannot be installed. */
export const PACK_DIGESTS: Record<string, PackDigest> = {
${body}
}

export function digestFor(code: string, set: 'fast' | 'best'): PackDigest | undefined {
  return PACK_DIGESTS[\`\${code}:\${set}\`]
}
`,
  'utf8',
)
console.log(`\nwrote ${rows.length} digests for tag ${TAG}`)
void src

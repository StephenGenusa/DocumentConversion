/**
 * Vendor the reveal.js runtime into a TypeScript module.
 *
 * A deck must open with no network and no sibling files, so the engine, its CSS
 * and the notes plugin are inlined into every generated `.html`. That means the
 * writer needs them as STRINGS, and `src/core` cannot read them from disk:
 * it imports no `node:fs` at all, which is the property the browser build
 * depends on (see the browser-build spec).
 *
 * So they are generated into a committed module, the way `shell.ts` gets
 * highlight.js as a module rather than a file. reveal.js stays a
 * devDependency - nothing at runtime needs the package, only this script does.
 *
 * The theme is deliberately `simple` (5 KB), not `white` (561 KB): the stock
 * themes embed a webfont as base64, and paying half a megabyte per deck for a
 * typeface nobody asked for is not a trade worth making.
 *
 *   node scripts/build-reveal-assets.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// reveal.js publishes a restrictive `exports` map: neither package.json nor
// dist/* is resolvable through it. The bare specifier is, and it lands on
// dist/reveal.js, so walk up from there to the package root.
const require = createRequire(import.meta.url)
const pkg = dirname(dirname(require.resolve('reveal.js')))
const version = JSON.parse(await readFile(join(pkg, 'package.json'), 'utf8')).version
const OUT = join(dirname(fileURLToPath(import.meta.url)), '../src/core/assets/reveal.generated.ts')

const read = (p) => readFile(join(pkg, 'dist', p), 'utf8')
const [engine, base, reset, theme, notes] = await Promise.all([
  read('reveal.js'),
  read('reveal.css'),
  read('reset.css'),
  read('theme/simple.css'),
  read('plugin/notes.js'),
])

/** Backtick-safe: the payload is minified JS and CSS, both of which contain them. */
const lit = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'

await writeFile(
  OUT,
  `/* eslint-disable */
// GENERATED by scripts/build-reveal-assets.mjs — do not edit.
// reveal.js ${version}, MIT, (C) Hakim El Hattab and contributors.
// Regenerate with: node scripts/build-reveal-assets.mjs

export const REVEAL_VERSION = ${JSON.stringify(version)}
export const REVEAL_JS = ${lit(engine)}
export const REVEAL_CSS = ${lit(reset + '\n' + base + '\n' + theme)}
export const REVEAL_NOTES_PLUGIN = ${lit(notes)}
`,
  'utf8',
)
const kb = (s) => Math.round(s.length / 1024)
console.log(
  `reveal.generated.ts written — engine ${kb(engine)} KB, css ${kb(reset + base + theme)} KB, notes ${kb(notes)} KB`,
)
